export function getWorkBySlug(slug: string): WorkProject | undefined {
  return WORK_PROJECTS.find((p) => p.slug === slug);
}

function resolveImage(slug: string, raw: string): string {
  if (REAL_IMAGES[slug]) return REAL_IMAGES[slug];
  const filename = raw.split("/").pop() || "";
  const KNOWN = Object.values(REAL_IMAGES).map(v => v.split("/").pop());
  if (KNOWN.includes(filename)) return raw;
  return fallbackImage(slug);
}

export function resolveWorkImages(project: WorkProject): WorkProject {
  const img = resolveImage(project.slug, project.image);
  const bentos = project.bentoImages.map((b) => resolveImage(project.slug, b));
  return { ...project, image: img, bentoImages: bentos };
}

export function getRelatedProjects(project: WorkProject): WorkProject[] {
  return project.relatedSlugs
    .map((s) => getWorkBySlug(s))
    .filter((p): p is WorkProject => p !== undefined);
}

